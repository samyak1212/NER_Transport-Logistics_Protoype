export function getRoutesForState(targetState) {
  if (!targetState || targetState === 'ALL' || targetState === 'MDoNER' || targetState === 'Central') {
    return DISTRICT_CONNECTIVITY_ROUTES;
  }
  return DISTRICT_CONNECTIVITY_ROUTES.filter(r => 
    r.fromState === targetState || r.toState === targetState
  );
}

/**
 * Filter districts by state involvement:
 * Returns districts within the targetState plus gateway districts connected to it.
 */
export function getDistrictsForState(targetState) {
  const allDistricts = Object.values(DISTRICT_CENTROIDS);
  if (!targetState || targetState === 'ALL' || targetState === 'MDoNER' || targetState === 'Central') {
    return allDistricts;
  }
  
  // Find districts that are in targetState OR connected to targetState via routes
  const connectedDistrictNames = new Set();
  DISTRICT_CONNECTIVITY_ROUTES.forEach(r => {
    if (r.fromState === targetState) {
      connectedDistrictNames.add(r.fromDistrict);
      connectedDistrictNames.add(r.toDistrict);
    }
    if (r.toState === targetState) {
      connectedDistrictNames.add(r.fromDistrict);
      connectedDistrictNames.add(r.toDistrict);
    }
  });

  return allDistricts.filter(d => d.state === targetState || connectedDistrictNames.has(d.name));
}

// Graph adjacency list for multi-hop route assembly
let _routeGraph = null;
function getRouteGraph() {
  if (_routeGraph) return _routeGraph;
  _routeGraph = {};
  DISTRICT_CONNECTIVITY_ROUTES.forEach(r => {
    if (!_routeGraph[r.fromDistrict]) _routeGraph[r.fromDistrict] = [];
    if (!_routeGraph[r.toDistrict]) _routeGraph[r.toDistrict] = [];
    _routeGraph[r.fromDistrict].push({ to: r.toDistrict, route: r, reversed: false });
    _routeGraph[r.toDistrict].push({ to: r.fromDistrict, route: r, reversed: true });
  });
  return _routeGraph;
}

/**
 * Finds a direct or multi-hop connected route between two districts with real road geometry.
 */
export function findConnectingRoute(fromDistrict, toDistrict) {
  if (!fromDistrict || !toDistrict || fromDistrict === 'ALL' || toDistrict === 'ALL' || fromDistrict === toDistrict) {
    return null;
  }

  // 1. Direct Route Check
  const direct = DISTRICT_CONNECTIVITY_ROUTES.find(r => 
    (r.fromDistrict === fromDistrict && r.toDistrict === toDistrict) ||
    (r.fromDistrict === toDistrict && r.toDistrict === fromDistrict)
  );

  if (direct) {
    const isForward = direct.fromDistrict === fromDistrict;
    return {
      ...direct,
      coordinates: isForward ? direct.coordinates : direct.coordinates.slice().reverse(),
      fromDistrict,
      toDistrict,
      fromState: isForward ? direct.fromState : direct.toState,
      toState: isForward ? direct.toState : direct.fromState,
      isDirect: true
    };
  }

  // 2. Multi-hop Breadth-First-Search across regional arterial highway network
  const graph = getRouteGraph();
  const queue = [[fromDistrict, []]];
  const visited = new Set([fromDistrict]);

  while (queue.length > 0) {
    const [curr, path] = queue.shift();
    if (curr === toDistrict) {
      let stitchedCoords = [];
      let totalDist = 0;
      let totalTime = 0;
      let totalDelay = 0;
      const highways = [];
      const conditions = [];
      const chokepoints = [];
      const bypasses = [];
      const bridges = [];
      let worstStatus = 'SMOOTH';
      let worstColor = '#22c55e';

      const statusWeights = { 'BLOCKED': 4, 'CONGESTED': 3, 'MODERATE': 2, 'SMOOTH': 1 };

      path.forEach(edge => {
        totalDist += edge.route.distance_km;
        totalTime += edge.route.travel_time_hrs;
        totalDelay += (edge.route.delay_mins || 0);
        highways.push(edge.route.highway);
        conditions.push(`${edge.to}: ${edge.route.condition}`);
        if (edge.route.active_chokepoints) chokepoints.push(edge.route.active_chokepoints);
        if (edge.route.alternative_bypass) bypasses.push(edge.route.alternative_bypass);
        if (edge.route.bridge_or_tunnel) bridges.push(edge.route.bridge_or_tunnel);

        if ((statusWeights[edge.route.traffic_status] || 1) > (statusWeights[worstStatus] || 1)) {
          worstStatus = edge.route.traffic_status;
          worstColor = edge.route.traffic_color;
        }

        const coords = edge.reversed 
          ? edge.route.coordinates.slice().reverse() 
          : edge.route.coordinates;

        if (stitchedCoords.length > 0) {
          stitchedCoords = stitchedCoords.concat(coords.slice(1));
        } else {
          stitchedCoords = stitchedCoords.concat(coords);
        }
      });

      const origData = DISTRICT_CENTROIDS[fromDistrict];
      const destData = DISTRICT_CENTROIDS[toDistrict];
      const hops = [fromDistrict, ...path.map(e => e.to)];

      return {
        id: `ROUTE_MULTI_${fromDistrict}_${toDistrict}`.replace(/\s+/g, '_'),
        name: `${fromDistrict} to ${toDistrict} Connected Arterial Corridor (${path.length} Hops)`,
        fromDistrict,
        toDistrict,
        fromState: origData?.state || '',
        toState: destData?.state || '',
        highway: Array.from(new Set(highways)).join(' ➔ '),
        distance_km: Number(totalDist.toFixed(1)),
        travel_time_hrs: Number(totalTime.toFixed(1)),
        traffic_status: worstStatus,
        traffic_color: worstColor,
        traffic_speed_kmh: Math.round((totalDist / Math.max(0.5, totalTime))),
        normal_speed_kmh: 55,
        delay_mins: totalDelay,
        condition: conditions.join(' • '),
        active_chokepoints: chokepoints.join('; ') || 'No critical chokepoints reported',
        alternative_bypass: bypasses.join('; ') || 'Follow regional diversion signboards',
        bridge_or_tunnel: bridges.join('; ') || 'Multiple river crossings',
        coordinates: stitchedCoords,
        isDirect: false,
        isMultiHop: true,
        hops
      };
    }

    for (const edge of (graph[curr] || [])) {
      if (!visited.has(edge.to)) {
        visited.add(edge.to);
        queue.push([edge.to, [...path, edge]]);
      }
    }
  }

  return null;
}

